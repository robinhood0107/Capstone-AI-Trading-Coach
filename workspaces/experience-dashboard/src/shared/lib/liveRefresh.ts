/**
 * 살아 있는 화면의 갱신 주기.
 *
 * `useResource` 는 처음부터 `refreshIntervalMs` 를 받도록 만들어져 있었다 — 연속 실패
 * 백오프, 숨은 탭에서 조회 중단, 창으로 돌아오면 즉시 재조회, 실패해도 마지막 성공 값
 * 유지까지 전부 들어 있다. **그런데 어느 화면도 그 인자를 넘기지 않았다.** 전부 1회
 * 로드였고, 그래서 장중에 체결이 일어나도 새로고침하기 전까지 화면이 그대로였다.
 *
 * 값을 화면마다 따로 적지 않고 여기 둔다. 초 단위를 화면마다 흩어 놓으면 "이 화면은 왜
 * 30초인가"를 아무도 설명하지 못하게 된다.
 */

/**
 * 거래가 진행되는 화면 — 현황, 자동운용, 체결 내역.
 *
 * 15초인 이유: 모의계좌 체결은 초 단위로 갱신되므로 분 단위는 너무 느리고, 그보다 짧으면
 * 사람이 읽는 속도보다 화면이 먼저 바뀐다. 헬스체크가 이미 6초마다 돌고 있어 이 정도
 * 추가 부하는 문제가 되지 않는다.
 */
export const LIVE_REFRESH_MS = 15_000;

/**
 * 하루 단위로만 바뀌는 화면 — 성과 보고서, 백테스트, 모델 비교.
 *
 * 이 값들은 장전 배치가 만든다. 자주 물어도 같은 답이 오므로 5분이면 충분하다.
 */
export const SLOW_REFRESH_MS = 300_000;
